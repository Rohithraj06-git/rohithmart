package com.rohith.rohithmart.dto;

import com.rohith.rohithmart.model.Role;

/**
 * Request DTO for user registration.
 * Security Note: Raw password is masked in toString() to prevent credential exposure in logs.
 */
public class RegisterRequest {
    private String name;
    private String email;
    private String password;
    private Role role;

    public RegisterRequest() {
    }

    public RegisterRequest(String name, String email, String password, Role role) {
        this.name = name;
        this.email = email;
        this.password = password;
        this.role = role;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPassword() {
        return password;
    }

    public void setPassword(String password) {
        this.password = password;
    }

    public Role getRole() {
        return role;
    }

    public void setRole(Role role) {
        this.role = role;
    }

    @Override
    public String toString() {
        return "RegisterRequest{" +
                "name='" + name + '\'' +
                ", email='" + email + '\'' +
                ", password='[MASKED]'" +
                ", role=" + role +
                '}';
    }
}
